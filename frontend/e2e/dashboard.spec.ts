import { test, expect } from '@playwright/test'
import type { Page } from '@playwright/test'

const password = 'Browser tests password 123!'
async function login(page: Page) {
  await page.goto('/')
  await page.getByLabel('Email address').fill('admin@example.com')
  await page.getByLabel('Password').fill(password)
  await page.getByRole('button', { name: 'Sign in' }).click()
  await expect(page.getByRole('heading', { name: 'Find your next drive.' })).toBeVisible()
}

test('registration, filtering, purchase, empty stock, reload and logout', async ({ page }) => {
  await page.goto('/#/register')
  await page.getByLabel('Full name').fill('Browser Customer')
  await page.getByLabel('Email address').fill('customer@example.com')
  await page.getByLabel('Password').fill(password)
  await page.getByRole('button', { name: 'Create account' }).click()
  await expect(page.getByRole('article')).toHaveCount(3)
  await expect(page.getByRole('button', { name: 'Add vehicle' })).toHaveCount(0)
  await expect(page.getByRole('article', { name: 'Honda Civic' }).getByRole('button')).toBeDisabled()
  await page.getByLabel('Make', { exact: true }).fill('toyota')
  await page.getByLabel('Model', { exact: true }).fill('Corolla')
  await page.getByLabel('Category', { exact: true }).fill('Sedan')
  await page.getByLabel('Min price').fill('25000.50')
  await page.getByLabel('Max price').fill('25000.50')
  await page.getByRole('button', { name: 'Apply filters' }).click()
  await expect(page.getByRole('article')).toHaveCount(1)
  await page.getByRole('button', { name: 'Purchase vehicle' }).click()
  await page.getByRole('button', { name: 'Confirm purchase' }).click()
  await expect(page.getByRole('status').filter({ hasText: 'Purchase successful' })).toBeVisible()
  await expect(page.getByRole('article').getByRole('button')).toBeDisabled()
  await page.reload()
  await expect(page.getByRole('article')).toHaveCount(3)
  await page.getByRole('button', { name: 'Sign out' }).click()
  await expect(page.getByRole('heading', { name: 'Welcome back.' })).toBeVisible()
})

test('admin adds, edits and deletes a vehicle with optional year', async ({ page }) => {
  await login(page)
  await page.getByRole('button', { name: 'Add vehicle' }).click()
  const dialog = page.getByRole('dialog')
  await dialog.getByLabel('Make', { exact: true }).fill('Mazda')
  await dialog.getByLabel('Model', { exact: true }).fill('MX-5')
  await dialog.getByLabel('Category', { exact: true }).fill('Convertible')
  await dialog.getByLabel('Price', { exact: true }).fill('32000.25')
  await dialog.getByLabel('Quantity in stock').fill('2')
  await dialog.getByRole('button', { name: 'Save vehicle' }).click()
  const card = page.getByRole('article', { name: 'Mazda MX-5' })
  await expect(card).toContainText('2 in stock')
  await card.getByRole('button', { name: 'Edit vehicle' }).click()
  await dialog.getByLabel('Quantity in stock').fill('5')
  await dialog.getByRole('button', { name: 'Save vehicle' }).click()
  await expect(card).toContainText('5 in stock')
  await card.getByRole('button', { name: 'Delete', exact: true }).click()
  await dialog.getByRole('button', { name: 'Cancel', exact: true }).click()
  await expect(card).toBeVisible()
  await card.getByRole('button', { name: 'Delete', exact: true }).click()
  await dialog.getByRole('button', { name: 'Confirm delete' }).click()
  await expect(card).toHaveCount(0)
})

