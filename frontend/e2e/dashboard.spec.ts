test('loading, server failure recovery and rejected session', async ({ page }) => {
  await page.route('**/api/vehicles', async route => {
    await new Promise(resolve => setTimeout(resolve, 500))
    await route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ detail: 'Temporarily unavailable' }) })
  })
  await login(page)
  await expect(page.getByRole('status')).toContainText('Loading the collection')
  await expect(page.getByRole('alert')).toContainText('Temporarily unavailable')
  await page.unroute('**/api/vehicles')
  await page.getByRole('button', { name: 'Refresh inventory' }).click()
  await expect(page.getByRole('article')).toHaveCount(3)
  await page.route('**/api/vehicles', route => route.fulfill({ status: 401, contentType: 'application/json', body: '{"detail":"Invalid or expired authentication token"}' }))
  await page.getByRole('button', { name: 'Clear filters' }).click()
  await expect(page.getByRole('heading', { name: 'Welcome back.' })).toBeVisible()
  await expect(page.getByRole('status')).toContainText('session is no longer valid')
})
