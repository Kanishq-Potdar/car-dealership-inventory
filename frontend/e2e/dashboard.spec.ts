test('customer desktop/mobile layout, loading, server recovery and expired session', async ({ page }) => {
  await login(page)
  await page.screenshot({ path: 'test-results/storefront-desktop.png', fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy()
  await page.screenshot({ path: 'test-results/storefront-mobile.png', fullPage: true })
  await page.route('**/api/vehicles', async route => {
    await new Promise(resolve => setTimeout(resolve, 1000))
    await route.fulfill({ status: 503, contentType: 'application/json', body: '{"detail":"Temporarily unavailable"}' })
  })
  await page.getByRole('button', { name: 'Clear filters' }).click()
  await expect(page.getByRole('status')).toContainText('Loading the collection')
  await expect(page.getByRole('alert')).toContainText('Temporarily unavailable')
  await page.unroute('**/api/vehicles')
  await page.getByRole('button', { name: 'Refresh inventory' }).click()
  await expect(page.getByRole('article')).toHaveCount(3)
  await page.route('**/api/vehicles', route => route.fulfill({ status: 401, contentType: 'application/json', body: '{"detail":"Invalid or expired authentication token"}' }))
  await page.getByRole('button', { name: 'Clear filters' }).click()
  await expect(page.getByRole('heading', { name: 'Welcome back.' })).toBeVisible()
  await expect(page.getByRole('status')).toContainText('session is no longer valid')
})

test('alert API failure is visible without hiding inventory', async ({ page }) => {
  await page.route('**/api/vehicles/alerts', route => route.fulfill({ status: 503, contentType: 'application/json', body: '{"detail":"Alerts unavailable"}' }))
  await login(page, true)
  await expect(page.getByRole('alert')).toContainText('Stock alerts unavailable')
  await expect(page.getByRole('button', { name: 'Purchase vehicle' })).toHaveCount(0)
  await page.unroute('**/api/vehicles/alerts')
  await page.getByRole('button', { name: 'Retry alerts' }).click()
  await expect(page.getByRole('button', { name: /^Low stock/ })).toBeVisible()
})
