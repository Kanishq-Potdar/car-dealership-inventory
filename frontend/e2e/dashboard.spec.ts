test('admin rows, price editing, atomic adjustments, CRUD and stock alerts', async ({ page }) => {
  await login(page, true)
  await expect(page.getByRole('button', { name: 'Purchase vehicle' })).toHaveCount(0)
  await expect(page.getByRole('article')).toHaveCount(0)
  await expect(page.getByRole('region', { name: 'Stock alerts' })).toContainText('3 units or fewer')
  await page.getByRole('button', { name: /^Out of stock/ }).click()
  const rows = page.getByRole('table').locator('tbody tr')
  for (const row of await rows.all()) await expect(row).toContainText('Out of stock')
  await page.getByRole('button', { name: 'All inventory', exact: true }).click()
  await page.getByRole('button', { name: 'Add vehicle' }).click()
  const dialog = page.getByRole('dialog')
  await dialog.getByLabel('Make', { exact: true }).fill('Mazda')
  await dialog.getByLabel('Model', { exact: true }).fill('MX-5')
  await dialog.getByLabel('Category', { exact: true }).fill('Convertible')
  await dialog.getByRole('combobox', { name: 'Condition', exact: true }).selectOption('new')
  await dialog.getByLabel('Price', { exact: true }).fill('32000.25')
  await dialog.getByLabel('Quantity in stock').fill('2')
  await dialog.getByRole('button', { name: 'Save vehicle' }).click()
  const row = page.getByRole('row', { name: 'Mazda MX-5', exact: true })
  await expect(row).toContainText('2 in stock')
  await row.getByRole('button', { name: 'Edit price', exact: true }).click()
  await dialog.getByLabel('Price', { exact: true }).fill('33000.75')
  await dialog.getByRole('button', { name: 'Save vehicle' }).click()
  await expect(row).toContainText('33,000.75')
  await expect(row).toContainText('2 in stock')
  for (const [operation, amount, stock] of [['increase', '3', '5'], ['decrease', '2', '3']]) {
    await row.getByRole('button', { name: 'Adjust stock', exact: true }).click()
    await dialog.getByLabel('Operation').selectOption(operation)
    await dialog.getByLabel('Units', { exact: true }).fill(amount)
    const request = page.waitForRequest(request => request.url().includes('/adjust-stock') && request.method() === 'POST')
    await dialog.getByRole('button', { name: 'Apply adjustment' }).click()
    expect((await request).postDataJSON()).toEqual({ delta: Number(amount) * (operation === 'decrease' ? -1 : 1) })
    await expect(row).toContainText(`${stock} in stock`)
  }
  await expect(row).toContainText('Low stock')
  await row.getByRole('button', { name: 'Adjust stock', exact: true }).click()
  await dialog.getByLabel('Operation').selectOption('decrease')
  await dialog.getByLabel('Units', { exact: true }).fill('10')
  await dialog.getByRole('button', { name: 'Apply adjustment' }).click()
  await expect(dialog.getByRole('alert')).toContainText('Vehicle out of stock')
  await dialog.getByRole('button', { name: 'Close dialog' }).click()
  await expect(row).toContainText('3 in stock')
  await row.getByRole('button', { name: 'Edit vehicle', exact: true }).click()
  await dialog.getByRole('combobox', { name: 'Condition', exact: true }).selectOption('used')
  await dialog.getByRole('button', { name: 'Save vehicle' }).click()
  await expect(row).toContainText('Used')
  await row.getByRole('button', { name: 'Delete', exact: true }).click()
  await dialog.getByRole('button', { name: 'Cancel', exact: true }).click()
  await expect(row).toBeVisible()
  await row.getByRole('button', { name: 'Delete', exact: true }).click()
  await dialog.getByRole('button', { name: 'Confirm delete' }).click()
  await expect(row).toHaveCount(0)
  await page.screenshot({ path: 'test-results/admin-inventory.png', fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy()
})

