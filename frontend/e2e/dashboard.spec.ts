import { test, expect } from '@playwright/test'
import type { Page } from '@playwright/test'

const password = 'Browser tests password 123!'
async function login(page: Page, admin = false) {
  await page.goto('/')
  await page.getByLabel('Email address').fill(admin ? 'admin@example.com' : 'shopper@example.com')
  await page.getByLabel('Password').fill(password)
  await page.getByRole('button', { name: 'Sign in' }).click()
  await expect(page.getByRole('heading', { name: admin ? 'Inventory, in control.' : 'Find your next drive.' })).toBeVisible()
  if (admin) await expect(page.getByRole('table')).toBeVisible()
  else await expect(page.getByRole('article')).toHaveCount(3)
}
const options = (page: Page, title: string) => page.getByRole('group', { name: `${title} options` })

test('registration, customer-only purchasing, persistence and backend authorization', async ({ page }) => {
  await page.goto('/#/register')
  await page.getByLabel('Full name').fill('Browser Customer')
  await page.getByLabel('Email address').fill('registered@example.com')
  await page.getByLabel('Password').fill(password)
  await page.getByRole('button', { name: 'Create account' }).click()
  await expect(page.getByRole('article')).toHaveCount(3)
  for (const name of ['Add vehicle', 'Edit vehicle', 'Adjust stock', 'Delete']) await expect(page.getByRole('button', { name, exact: false })).toHaveCount(0)
  await expect(page.getByRole('article', { name: 'Honda Civic' }).getByRole('button')).toBeDisabled()
  const statuses = await page.evaluate(async () => {
    const headers = { Authorization: `Bearer ${sessionStorage.getItem('dealership-token')}`, 'Content-Type': 'application/json' }
    return [(await fetch('/api/vehicles/1/adjust-stock', { method: 'POST', headers, body: '{"delta":1}' })).status,
      (await fetch('/api/vehicles/alerts', { headers })).status]
  })
  expect(statuses).toEqual([403, 403])
  const card = page.getByRole('article', { name: 'Toyota Corolla' })
  await card.getByRole('button', { name: 'Purchase vehicle' }).click()
  await page.getByRole('button', { name: 'Confirm purchase' }).click()
  await expect(page.getByRole('status').filter({ hasText: 'Purchase successful' })).toBeVisible()
  await expect(card.getByRole('button')).toBeDisabled()
  await page.reload()
  await expect(card.getByRole('button')).toBeDisabled()
  await page.getByRole('button', { name: 'Sign out' }).click()
  await expect(page.getByRole('heading', { name: 'Welcome back.' })).toBeVisible()
})

test('multi-select filters combine, model choices follow brands, condition and sorting', async ({ page }) => {
  await login(page)
  await page.getByLabel('Search brand options').fill('toy')
  await expect(options(page, 'Brand').getByLabel('Honda', { exact: true })).toHaveCount(0)
  await options(page, 'Brand').getByLabel('Toyota', { exact: true }).check()
  await page.getByLabel('Search brand options').fill('')
  await options(page, 'Brand').getByLabel('Honda', { exact: true }).check()
  await options(page, 'Category').getByLabel('Sedan', { exact: true }).check()
  await options(page, 'Category').getByLabel('SUV', { exact: true }).check()
  await page.getByRole('button', { name: 'Apply filters' }).click()
  await expect(page.getByRole('article')).toHaveCount(3)
  await page.getByLabel('Sort by').selectOption('price-desc')
  await expect(page.getByRole('article').first()).toHaveAttribute('aria-label', 'Toyota RAV4')
  await page.getByRole('combobox', { name: 'Condition', exact: true }).selectOption('new')
  await page.getByRole('button', { name: 'Apply filters' }).click()
  await expect(page.getByRole('article')).toHaveCount(1)
  await expect(page.getByRole('article')).toHaveAttribute('aria-label', 'Toyota RAV4')
  await page.getByRole('combobox', { name: 'Condition', exact: true }).selectOption('used')
  await page.getByLabel('Search model options').fill('cor')
  await options(page, 'Model').getByLabel('Corolla', { exact: true }).check()
  await page.getByRole('button', { name: 'Apply filters' }).click()
  await expect(page.getByRole('article')).toHaveCount(1)
  await expect(page.getByRole('article')).toHaveAttribute('aria-label', 'Toyota Corolla')
  await options(page, 'Brand').getByLabel('Toyota', { exact: true }).uncheck()
  await page.getByLabel('Search model options').fill('')
  await expect(options(page, 'Model').getByLabel('Corolla', { exact: true })).toHaveCount(0)
  await expect(options(page, 'Model').getByLabel('Civic', { exact: true })).not.toBeChecked()
  await page.getByRole('button', { name: 'Apply filters' }).click()
  await expect(page.getByRole('article')).toHaveCount(1)
  await expect(page.getByRole('article')).toHaveAttribute('aria-label', 'Honda Civic')
})

